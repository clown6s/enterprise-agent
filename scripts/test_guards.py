# -*- coding: utf-8 -*-
"""
guards.fix_output 形态测试矩阵（格式重建引擎的契约）：
每个历史实况 = 一条用例；改 guards 先跑这里再跑回归。
跑法：python scripts/test_guards.py
"""
import sys

sys.path.insert(0, ".")

from app import guards

CASES = []


def case(name, text, *expects):
    CASES.append((name, text, list(expects)))


# 1. 编号条目归一（1. / 1、）
case("编号点号归一", "1. 感知工具：让 Agent 访问信息\n2. 记忆系统：存储上下文",
     "- 感知工具：让 Agent 访问信息", "- 记忆系统：存储上下文")
out1 = guards.fix_output("1. 感知工具：让 Agent 访问信息\n2. 记忆系统：存储上下文")
assert "1. " not in out1 and "2. " not in out1

# 2. 编号防误伤：1.5倍/日期行
case("编号防误伤", "目标值 1.5倍\n2024.01.01 生效",
     "1.5倍", "2024.01.01")

# 3. （1）式编号归一
case("括号编号归一", "（1）感知工具：让 Agent 访问信息\n（2）记忆系统：存储上下文",
     "- 感知工具：让 Agent 访问信息", "- 记忆系统：存储上下文")

# 4. ① 式编号归一（医学资料原文形态）
case("圈号归一", "①窦速\n②窦缓",
     "- 窦速", "- 窦缓")

# 5. 无序符号归一（CJK-拉丁补空格是规范行为："条目A" → "条目 A"）
case("无序归一", "* 条目A\n• 条目B",
     "- 条目 A", "- 条目 B")

# 6. 裸标题带冒号 + 裸条目恢复（历史实况：高血压卡）
case("裸标题冒号恢复",
     "血压控制目标值：\n130/80以下\n坚持规律服药",
     "**血压控制目标值**：", "- 130/80以下", "- 坚持规律服药")

# 7. 裸标题无冒号 + 分号结尾条目（新实况：出血程度评估）
case("裸标题无冒号分号条目",
     "出血程度评估\n成人每日消化道出血 >5～10ml → 粪便隐血试验阳性；\n每日出血量50～100ml → 可出现黑粪；",
     "**出血程度评估**", "- 成人每日消化道出血 >5～10ml → 粪便隐血试验阳性；",
     "- 每日出血量50～100ml → 可出现黑粪；")

# 8. 首行裸标题加粗（新实况：上消化道出血）
case("首行裸标题",
     "上消化道出血\n定义：指从食管到屈氏韧带之间消化道的出血。",
     "**上消化道出血**\n定义：")

# 9. 分隔线删除（新实况：--- 是模型自创元素）
case("分隔线删除",
     "**标题**\n内容一\n---\n内容二",
     "**标题**", "内容一", "内容二")
out9 = guards.fix_output("**标题**\n内容一\n---\n内容二")
assert "---" not in out9, out9

# 10. 图谱三元组行删除
case("三元组删除",
     "红旗渠 --[与...同属]--> 云台山\n正常内容",
     "正常内容")
out10 = guards.fix_output("红旗渠 --[与...同属]--> 云台山\n正常内容")
assert "--[" not in out10

# 11. 图谱回声块删除（≥3 行）
case("回声块删除",
     "高血压（属于）：恶性高血压、高血压亚急症\n心脏病（属于）：冠心病\n糖尿病（属于）：1型\n正常内容",
     "正常内容")
out11 = guards.fix_output(
    "高血压（属于）：恶性高血压、高血压亚急症\n心脏病（属于）：冠心病\n糖尿病（属于）：1型\n正常内容")
assert "（属于）" not in out11

# 12. 题干句式首行剥除
case("题干剥除", "描写告别的方法\n正文内容开始",
     "正文内容开始")
out12 = guards.fix_output("描写告别的方法\n正文内容开始")
assert not out12.startswith("描写")

# 13. 孤立编号行合并
case("孤立编号合并", "1.\n内容", "- 内容")

# 14. 定义行序列恢复（≥3 行）
case("定义行恢复",
     "感知工具：让 Agent 访问信息\n记忆系统：存储上下文\n规划能力：分解任务",
     "- 感知工具：让 Agent 访问信息", "- 记忆系统：存储上下文", "- 规划能力：分解任务")

# 15. 散文不误伤（行内多句/长行防线）
case("散文防线",
     "这是一段正常的多句散文。它包含句号。\n下一段也是完整的内容。",
     "这是一段正常的多句散文。它包含句号。", "下一段也是完整的内容。")

# 16. 结尾悬空编号 + 半截句清理
case("结尾残句",
     "内容一\n内容二\n3.",
     "内容一", "内容二")
out16 = guards.fix_output("内容一\n内容二\n3.")
assert not out16.endswith("3.")

# 17. 双重编号防（编号定义行不再回填前缀）
case("双重编号防",
     "1. 感知工具：让 Agent 访问信息\n2. 记忆系统：存储上下文\n3. 规划能力：分解任务",
     "- 感知工具：让 Agent 访问信息")
out17 = guards.fix_output(
    "1. 感知工具：让 Agent 访问信息\n2. 记忆系统：存储上下文\n3. 规划能力：分解任务")
assert "1. 1." not in out17 and "（1）" not in out17

# 17b. 裸标题后随散文：标题加粗、散文原样（"临床表现"实况）
case("裸标题散文内容",
     "临床表现\n呕血与黑便：为上消化道出血的特征性表现。呕血多呈咖啡渣样；黑粪呈柏油样。",
     "**临床表现**\n呕血与黑便：为上消化道出血的特征性表现。呕血多呈咖啡渣样；黑粪呈柏油样。")

# 18. 幂等
IDEM = guards.fix_output(
    "血压控制目标值：\n130/80以下\n坚持规律服药\n---\n出血程度评估\n每日出血量50～100ml → 可出现黑粪；\n胃内储积血量 >250ml → 可引起呕血；")
assert guards.fix_output(IDEM) == IDEM, "fix_output 非幂等"

failed = 0
for name, text, expects in CASES:
    out = guards.fix_output(text)
    bad = [e for e in expects if e not in out]
    if bad:
        failed += 1
        print(f"✗ {name}: 缺少 {bad}\n  输出: {out!r}")
    else:
        print(f"✓ {name}")
print(f"\n{len(CASES) - failed}/{len(CASES)} 通过" + ("（含幂等检查）" if not failed else ""))
sys.exit(1 if failed else 0)
