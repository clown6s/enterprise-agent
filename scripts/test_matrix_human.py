total_ok, total_all = 0, 0
fails = []
for case in CASES:
    name, variants, cid, must, forbid = case[0], case[1], case[2], case[3], case[4]
    must_any = case[5] if len(case) > 5 else None
    ok = 0
    sample = ""
    for i in range(N):
        q = variants[i % len(variants)]
        try:
            r = agent.answer(q, conversation_id=f"{cid}_{i}", user="admin")
            ans = r.get("answer", "")
        except Exception as e:
            sample = sample or f"第{i + 1}次[{q}] EXC {e!r}"
            continue
        bad = False
        if must_any:
            bad = not any(all(m in ans for m in grp) for grp in must_any)
            if bad:
                sample = sample or f"第{i + 1}次[{q}] 缺任一组 → {ans[:90]}"
        else:
            for m in must:
                if m and m not in ans:
                    bad, sample = True, sample or f"第{i + 1}次[{q}] 缺[{m}] → {ans[:90]}"
        if not bad:
            for f in forbid:
                if f and f in ans:
                    bad, sample = True, sample or f"第{i + 1}次[{q}] 误含[{f}] → {ans[:90]}"
        if not bad:
            ok += 1
    total_ok += ok
    total_all += N
    print(f"{name}: {ok}/{N}", f" | {sample}" if sample else "")
    if ok < N:
        fails.append(name)

print(f"\n===== 汇总: {total_ok}/{total_all} =====")
